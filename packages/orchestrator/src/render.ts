import type {
  Architecture,
  BusinessAnalysis,
  DeploymentPlan,
  ManagerPlan,
  QaPlan,
  ReviewResult,
  UxSpec,
} from "@autodev/agents";

/** Markdown renderers used to persist planning artefacts inside the project. */

const header = (title: string): string => `${title}\n\n> Generated by AutoDev Agent. Edits made by the owner are preserved in Git history.\n`;

export function renderBusinessAnalysis(analysis: BusinessAnalysis): string {
  return [
    header("# Business Requirements Document"),
    "## Purpose and scope",
    analysis.brd,
    "",
    "## User stories",
    ...analysis.userStories.flatMap((story) => [
      `### ${story.id}`,
      `As a ${story.asA}, I want ${story.iWant}, so that ${story.soThat}.`,
      ...story.acceptanceCriteria.map((criterion) => `- ${criterion}`),
      "",
    ]),
    "## Acceptance criteria",
    ...analysis.acceptanceCriteria.map((criterion, index) => `${index + 1}. ${criterion}`),
    "",
    "## Open questions",
    ...(analysis.openQuestions.length > 0
      ? analysis.openQuestions.map((question) => `- ${question}`)
      : ["- None recorded."]),
    "",
  ].join("\n");
}

export function renderArchitecture(architecture: Architecture): string {
  return [
    header("# Solution Architecture"),
    "## Overview",
    architecture.overview,
    "",
    "## Components",
    ...architecture.components.map(
      (component) => `- **${component.name}** (${component.technology}) — ${component.responsibility}`,
    ),
    "",
    "## Data model",
    ...architecture.dataModel.flatMap((table) => [
      `### ${table.table}`,
      ...table.columns.map((column) => `- \`${column}\``),
      "",
    ]),
    "## API",
    ...architecture.api.map((route) => `- \`${route.method} ${route.path}\` — ${route.purpose}`),
    "",
    "## Decisions",
    ...architecture.decisions.map((decision) => `- **${decision.decision}** — ${decision.rationale}`),
    "",
    "## Risks",
    ...architecture.risks.map((risk) => `- ${risk}`),
    "",
  ].join("\n");
}

export function renderUx(ux: UxSpec): string {
  return [
    header("# UX Specification"),
    "## Design intent",
    ux.ux,
    "",
    "## Screens",
    ...ux.screens.flatMap((screen) => [
      `### ${screen.name} (\`${screen.route}\`)`,
      screen.purpose,
      `- Components: ${screen.components.join(", ") || "—"}`,
      `- States: ${screen.states.join(", ") || "—"}`,
      "",
    ]),
    "## Navigation",
    ...ux.navigation.map((item) => `- ${item}`),
    "",
    "## Design tokens",
    `- Colour: ${ux.designTokens.color.join(", ") || "—"}`,
    `- Spacing: ${ux.designTokens.spacing.join(", ") || "—"}`,
    `- Typography: ${ux.designTokens.typography.join(", ") || "—"}`,
    "",
    "## Accessibility",
    ...ux.accessibility.map((item) => `- ${item}`),
    "",
  ].join("\n");
}

export function renderQaPlan(plan: QaPlan): string {
  return [
    header("# QA Plan"),
    ...plan.scenarios.flatMap((scenario) => [
      `## ${scenario.id} — ${scenario.title}`,
      ...scenario.steps.map((step, index) => `${index + 1}. ${step}`),
      `**Expected:** ${scenario.expected}`,
      "",
    ]),
    plan.notes ? `_${plan.notes}_` : "",
    "",
  ].join("\n");
}

export function renderReview(review: ReviewResult): string {
  return [
    header("# Code Review"),
    `**Verdict:** ${review.verdict}`,
    "",
    review.summary,
    "",
    "## Issues",
    ...(review.issues.length > 0
      ? review.issues.map(
          (issue) =>
            `- **[${issue.severity}]** ${issue.file ? `\`${issue.file}\` — ` : ""}${issue.issue}\n  - Recommendation: ${issue.recommendation}`,
        )
      : ["- No issues found."]),
    "",
  ].join("\n");
}

export function renderDeployment(plan: DeploymentPlan): string {
  return [
    header("# Deployment Plan"),
    plan.notes,
    "",
    "## Configuration",
    ...plan.envVars.map(
      (variable) =>
        `- \`${variable.name}\`${variable.required ? " (required)" : " (optional)"} — ${variable.description}`,
    ),
    "",
    "## Healthcheck",
    plan.healthcheck ? `\`${plan.healthcheck}\`` : "Not specified.",
    "",
    `**Production ready:** ${plan.readyForProduction ? "yes" : "no — owner approval required"}`,
    "",
  ].join("\n");
}

export function renderManagerPlan(plan: ManagerPlan): string {
  return [
    header("# Delivery Plan"),
    "## Strategy",
    plan.strategy,
    "",
    "## Milestones",
    ...plan.milestones.map(
      (milestone) => `- **${milestone.title}** (${milestone.role}) — _done when:_ ${milestone.acceptanceCheck}`,
    ),
    "",
    "## Risks",
    ...(plan.risks.length > 0 ? plan.risks.map((risk) => `- ${risk}`) : ["- None recorded."]),
    "",
  ].join("\n");
}

export function renderEnvExample(
  envVars: Array<{ name: string; required: boolean; description: string }>,
): string {
  const lines = [
    "# Generated by AutoDev Agent. Never commit real secrets.",
    "PORT=4173",
    ...envVars
      .filter((variable) => variable.name.toUpperCase() !== "PORT")
      .map(
        (variable) =>
          `# ${variable.description}${variable.required ? " (required)" : ""}\n${variable.name}=`,
      ),
    "",
  ];
  return lines.join("\n");
}
