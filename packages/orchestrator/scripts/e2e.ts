/**
 * Full-stack end-to-end verification.
 *
 * Uses the real PostgreSQL database, the real Docker sandbox, the real git
 * wrapper and the deterministic scaffold engine to drive one project through
 * every phase, including the owner approval gate. Nothing is mocked and the
 * script fails loudly if any stage does not produce persisted evidence.
 *
 * Run with: pnpm --filter @autodev/orchestrator e2e
 */
import fs from "node:fs/promises";
import path from "node:path";

import {
  ArtifactsRepository,
  EventsRepository,
  ProjectsRepository,
  RequirementsRepository,
  TasksRepository,
  createDatabase,
} from "@autodev/db";
import { GitRepo } from "@autodev/git";
import { SandboxManager } from "@autodev/sandbox";
import { readConfig, type ActivityEventType } from "@autodev/shared";

import { EventBus } from "../src/event-bus.js";
import { Orchestrator } from "../src/orchestrator.js";

const root = path.join("/tmp/opencode", `autodev-e2e-${Date.now().toString(36)}`);
const workspacesRoot = path.join(root, "workspaces");

interface CheckResult {
  ok: boolean;
  name: string;
  detail: string;
}

const results: CheckResult[] = [];

async function check(name: string, run: () => Promise<string>): Promise<void> {
  const started = Date.now();
  try {
    const detail = await run();
    results.push({ ok: true, name, detail });
    console.log(`PASS  ${name}  ${detail} (${Date.now() - started}ms)`);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    results.push({ ok: false, name, detail });
    console.log(`FAIL  ${name}  ${detail}`);
  }
}

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

async function main(): Promise<void> {
  await fs.mkdir(workspacesRoot, { recursive: true });

  const config = readConfig({
    ...process.env,
    NODE_ENV: "test",
    WORKSPACES_ROOT: workspacesRoot,
    AUTODEV_ENGINE: "scaffold",
  });

  const database = createDatabase(config.DATABASE_URL);
  const projects = new ProjectsRepository(database.db);
  const tasks = new TasksRepository(database.db);
  const artifacts = new ArtifactsRepository(database.db);
  const requirements = new RequirementsRepository(database.db);
  const eventsRepo = new EventsRepository(database.db);
  const events = new EventBus({ events: eventsRepo });
  const sandbox = new SandboxManager({
    image: config.SANDBOX_IMAGE,
    limits: {
      memoryMb: config.SANDBOX_MEMORY_MB,
      cpus: config.SANDBOX_CPUS,
      pidsLimit: config.SANDBOX_PIDS_LIMIT,
      commandTimeoutMs: config.COMMAND_TIMEOUT_MS,
    },
  });

  const orchestrator = new Orchestrator({
    config,
    projects,
    tasks,
    artifacts,
    requirements,
    events,
    sandbox,
    maxRepairAttempts: 1,
    maxReviewRounds: 1,
    approvalTimeoutMs: 180_000,
    logger: (message, detail) => console.log(`[orchestrator] ${message}`, detail ?? ""),
  });

  const project = await projects.create({
    name: "E2E Task Tracker",
    description: "A tiny task tracker generated by the end-to-end verification run",
    requirements: [
      "A single page that lists tasks with a title and completion state.",
      "An API endpoint that reports application health.",
      "Playwright tests that prove the home page renders and the API responds.",
    ].join("\n"),
    techStack: ["Node.js", "Playwright", "Docker"],
    engine: "scaffold",
    workspacePath: path.join(workspacesRoot, "pending"),
  });
  await projects.update(project.id, {
    workspacePath: path.join(workspacesRoot, project.id),
  });

  console.log(`project ${project.id} in ${root}\n`);

  // Auto-approve the production gate the way the dashboard would.
  let pendingApproval: string | null = null;
  events.subscribe(project.id, (event) => {
    if (event.type === "approval.requested") {
      const id = event.payload.approvalId;
      if (typeof id === "string") pendingApproval = id;
    }
  });

  const approver = setInterval(() => {
    const id = pendingApproval;
    if (!id) return;
    pendingApproval = null;
    void orchestrator
      .decideApproval(id, "approved", "e2e@autodev.local", "approved by e2e script")
      .catch((error) => console.log(`[approver] ${String(error)}`));
  }, 250);

  try {
    await check("pipeline completes", async () => {
      await orchestrator.start(project.id);
      const final = await projects.findById(project.id);
      assert(final, "project disappeared");
      assert(final.status === "completed", `expected completed, got ${final.status}: ${final.error ?? ""}`);
      assert(final.progress === 100, `expected progress 100, got ${final.progress}`);
      return `${final.status} at ${final.progress}%`;
    });

    const final = await projects.findById(project.id);
    assert(final, "project disappeared");

    await check("all nine tasks succeeded", async () => {
      const rows = await tasks.listByProject(project.id);
      assert(rows.length === 9, `expected 9 tasks, got ${rows.length}`);
      const failed = rows.filter((row) => row.status !== "succeeded");
      assert(failed.length === 0, `not succeeded: ${failed.map((row) => `${row.phase}:${row.status}`).join(", ")}`);
      return `${rows.length} tasks succeeded`;
    });

    await check("requirements were persisted", async () => {
      const latest = await requirements.latest(project.id);
      assert(latest, "no requirements row");
      assert((latest.brd ?? "").length > 50, "BRD is too short to be real");
      assert(latest.acceptanceCriteria.length > 0, "no acceptance criteria");
      assert(latest.userStories.length > 0, "no user stories");
      return `${latest.userStories.length} stories, ${latest.acceptanceCriteria.length} criteria`;
    });

    await check("implementation files exist on disk and in the index", async () => {
      const workspace = path.join(workspacesRoot, project.id);
      const required = ["package.json", "server.mjs", "public/index.html", "tests/app.spec.ts"];
      for (const file of required) {
        const stat = await fs.stat(path.join(workspace, file)).catch(() => null);
        assert(stat?.isFile(), `missing ${file}`);
      }
      const indexed = await artifacts.listFiles(project.id);
      assert(indexed.length >= 6, `expected at least 6 indexed files, got ${indexed.length}`);
      const paths = new Set(indexed.map((row) => row.path));
      assert(paths.has("server.mjs"), "server.mjs not indexed");
      assert(!paths.has(".env"), ".env must never be indexed");
      return `${indexed.length} files indexed`;
    });

    await check("planning documents were written", async () => {
      const workspace = path.join(workspacesRoot, project.id);
      const docs = [
        "docs/DELIVERY-PLAN.md",
        "docs/BRD.md",
        "docs/ARCHITECTURE.md",
        "docs/UX.md",
        "docs/QA-PLAN.md",
        "docs/REVIEW.md",
        "docs/DEPLOYMENT.md",
        ".env.example",
      ];
      for (const doc of docs) {
        const content = await fs.readFile(path.join(workspace, doc), "utf8").catch(() => null);
        assert(content && content.length > 20, `missing or empty ${doc}`);
      }
      return `${docs.length} documents`;
    });

    await check("playwright tests really ran and passed", async () => {
      const rows = await artifacts.listTests(project.id);
      assert(rows.length > 0, "no test results recorded");
      const passed = rows.filter((row) => row.status === "passed");
      assert(passed.length > 0, `no passing run: ${rows.map((row) => row.status).join(", ")}`);
      const total = passed.reduce((sum, row) => sum + row.total, 0);
      assert(total > 0, "passing run recorded zero tests");
      const failures = passed.reduce((sum, row) => sum + row.failed, 0);
      assert(failures === 0, "a passing run contains failures");
      return `${rows.length} run(s), ${total} browser test(s) passed`;
    });

    await check("git checkpoints exist for each milestone", async () => {
      const git = new GitRepo({ repoPath: path.join(workspacesRoot, project.id) });
      const log = await git.log(50);
      assert(log.length >= 6, `expected at least 6 checkpoints, got ${log.length}`);
      const subjects = log.map((entry) => entry.subject);
      assert(subjects.some((subject) => subject.includes("implementation")), "no implementation checkpoint");
      assert(subjects.some((subject) => subject.includes("deployment")), "no deployment checkpoint");
      return `${log.length} commits, head ${log[0]?.commit.slice(0, 7)}`;
    });

    await check("review and deployment artifacts were persisted", async () => {
      const workspace = path.join(workspacesRoot, project.id);
      const reviewDoc = await fs.readFile(path.join(workspace, "docs/REVIEW.md"), "utf8");
      assert(/Verdict/.test(reviewDoc), "review doc has no verdict");
      const deployments = await artifacts.listDeployments(project.id);
      assert(deployments.length === 1, `expected 1 deployment, got ${deployments.length}`);
      assert(deployments[0]?.status === "prepared", `unexpected deployment status ${deployments[0]?.status}`);
      const dockerfile = await fs.readFile(path.join(workspace, "Dockerfile"), "utf8");
      assert(/FROM/.test(dockerfile), "Dockerfile has no FROM line");
      return `deployment ${deployments[0]?.version} prepared`;
    });

    await check("owner approval gate was exercised and recorded", async () => {
      const approvals = await artifacts.listApprovals(project.id);
      const deployment = approvals.find((row) => row.type === "production_deployment");
      assert(deployment, "no production approval row");
      assert(deployment.status === "approved", `expected approved, got ${deployment.status}`);
      assert(deployment.decidedBy === "e2e@autodev.local", `unexpected decider ${deployment.decidedBy}`);
      return `${deployment.status} by ${deployment.decidedBy}`;
    });

    await check("activity log captures every phase", async () => {
      const rows = await eventsRepo.list(project.id, { limit: 500 });
      const types = new Set(rows.map((row) => row.type));
      const required: ActivityEventType[] = [
        "project.started",
        "phase.started",
        "task.started",
        "file.written",
        "test.started",
        "test.completed",
        "checkpoint.created",
        "approval.requested",
        "approval.decided",
        "project.completed",
      ];
      for (const type of required) {
        assert(types.has(type), `missing event type ${type}`);
      }
      const phases = rows
        .filter((row) => row.type === "phase.completed")
        .map((row) => String(row.payload.phase));
      assert(phases.length === 9, `expected 9 completed phases, got ${phases.length}`);
      return `${rows.length} events, ${phases.length} phases`;
    });

    await check("preview server serves the generated app", async () => {
      const preview = await orchestrator.startPreview(project.id);
      assert(preview.url, "no preview url was published");
      assert(preview.url !== "http://127.0.0.1:4173", "preview port was not remapped");

      let lastError = "";
      for (let attempt = 0; attempt < 40; attempt += 1) {
        try {
          const response = await fetch(`${preview.url}/api/health`);
          if (response.ok) {
            const body = (await response.json()) as { status?: string };
            assert(body.status === "ok", `health payload ${JSON.stringify(body)}`);
            const html = await (await fetch(preview.url)).text();
            assert(html.includes("E2E Task Tracker"), "home page does not include the app name");
            return `${preview.url} served health + home page`;
          }
          lastError = `status ${response.status}`;
        } catch (error) {
          lastError = String(error);
        }
        await new Promise((resolve) => setTimeout(resolve, 250));
      }
      throw new Error(`preview unreachable: ${lastError}`);
    });

    await check("resuming a completed project is idempotent", async () => {
      const before = await artifacts.listFiles(project.id);
      await orchestrator.start(project.id);
      const after = await projects.findById(project.id);
      assert(after?.status === "completed", `expected completed, got ${after?.status}`);
      const afterFiles = await artifacts.listFiles(project.id);
      assert(afterFiles.length === before.length, "resume changed the file index");
      const runs = await artifacts.listTests(project.id);
      assert(runs.length > 0, "test history was lost");
      return "second run skipped completed tasks";
    });

    await check("policy still blocks dangerous commands at the API boundary", async () => {
      let blocked = false;
      try {
        await orchestrator.runCommand(project.id, { command: "rm -rf /" });
      } catch (error) {
        blocked = /blocked by policy/i.test(String(error));
      }
      assert(blocked, "rm -rf / was not blocked");
      return "rm -rf / rejected";
    });
  } finally {
    clearInterval(approver);

    const live = await projects.findById(project.id);
    if (live?.containerId) {
      await sandbox.removeContainer(live.containerId).catch((error) => {
        console.log(`[cleanup] container: ${String(error)}`);
      });
    }
    await database.close();
  }

  const failed = results.filter((result) => !result.ok);
  console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
  console.log(`workspace retained at ${root}`);
  process.exit(failed.length > 0 ? 1 : 0);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
