import fs from "node:fs/promises";
import path from "node:path";

import type { CodingEngine, CodingResult, CodingTask, CodingEventHandler } from "./types.js";
import {
  APP_JS,
  DOCKERFILE,
  DOCKERIGNORE,
  GITIGNORE,
  SERVER_MJS,
  STYLES_CSS,
  renderDocs,
  renderIndexHtml,
  renderPackageJson,
  renderPlaywrightConfig,
  renderReadme,
  renderTestSpec,
  type ScaffoldMeta,
} from "./templates.js";

/**
 * Deterministic engine used when no LLM credentials are configured.
 * It produces a real, runnable application — never a fake success response.
 */
export class ScaffoldEngine implements CodingEngine {
  readonly name = "scaffold" as const;

  isAvailable(): boolean {
    return true;
  }

  unavailableReason(): string | null {
    return null;
  }

  async run(task: CodingTask, onEvent: CodingEventHandler): Promise<CodingResult> {
    const meta = buildMeta(task);
    const files: Array<{ path: string; content: string }> = [
      { path: "package.json", content: renderPackageJson(meta) },
      { path: "app.config.json", content: JSON.stringify(meta, null, 2) },
      { path: "server.mjs", content: SERVER_MJS },
      { path: "public/index.html", content: renderIndexHtml(meta) },
      { path: "public/styles.css", content: STYLES_CSS },
      { path: "public/app.js", content: APP_JS },
      { path: "playwright.config.ts", content: renderPlaywrightConfig() },
      { path: "tests/app.spec.ts", content: renderTestSpec(meta) },
      { path: "README.md", content: renderReadme(meta) },
      { path: "Dockerfile", content: DOCKERFILE },
      { path: ".dockerignore", content: DOCKERIGNORE },
      { path: ".gitignore", content: GITIGNORE },
      ...renderDocs(meta, task.phaseContext),
    ];

    onEvent({ type: "log", message: `scaffold engine writing ${files.length} files` });

    const written: string[] = [];
    for (const file of files) {
      const absolute = safeJoin(task.workspacePath, file.path);
      await fs.mkdir(path.dirname(absolute), { recursive: true });
      await fs.writeFile(absolute, file.content, "utf8");
      written.push(file.path);
      onEvent({ type: "file", path: file.path });
    }

    return {
      engine: "scaffold",
      summary: `Scaffolded ${meta.appName} with ${meta.features.length} capabilities, API, Playwright tests and Dockerfile.`,
      filesWritten: written,
      commandsRun: [],
      transcript: `scaffold:${meta.appName}:${written.length} files`,
    };
  }
}

export function buildMeta(task: CodingTask): ScaffoldMeta {
  const features = extractFeatures(task.requirements);
  return {
    appName: task.appName,
    description: firstMeaningfulLine(task.requirements) || "An application generated by AutoDev Agent.",
    features,
    requirements: task.requirements.trim(),
  };
}

export function extractFeatures(requirements: string): Array<{ title: string; description: string }> {
  const candidates = requirements
    .split(/\r?\n|(?<=[.!?])\s+/)
    .map((line) => line.replace(/^[-*\d.)\s]+/, "").trim())
    .filter((line) => line.length >= 12 && !/^(tech stack|use |build )/i.test(line));

  const seen = new Set<string>();
  const features: Array<{ title: string; description: string }> = [];

  for (const candidate of candidates) {
    const words = candidate.split(/\s+/).slice(0, 6).join(" ");
    const key = words.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    features.push({ title: sentenceCase(words), description: candidate });
    if (features.length >= 6) break;
  }

  if (features.length === 0) {
    features.push(
      { title: "Core workflow", description: "Primary user journey described in the requirements." },
      { title: "Data API", description: "JSON API exposing application data." },
      { title: "Responsive UI", description: "Layouts that adapt to desktop and mobile screens." },
    );
  }

  return features;
}

function firstMeaningfulLine(text: string): string {
  const line = text
    .split(/\r?\n/)
    .map((value) => value.trim())
    .find((value) => value.length > 0);
  if (!line) return "";
  return line.length > 240 ? `${line.slice(0, 237)}...` : line;
}

function sentenceCase(value: string): string {
  if (!value) return value;
  return value.charAt(0).toUpperCase() + value.slice(1);
}

export function safeJoin(root: string, relativePath: string): string {
  const resolvedRoot = path.resolve(root);
  const resolved = path.resolve(resolvedRoot, relativePath);
  const prefix = resolvedRoot.endsWith(path.sep) ? resolvedRoot : `${resolvedRoot}${path.sep}`;
  if (resolved !== resolvedRoot && !resolved.startsWith(prefix)) {
    throw new Error(`Refusing to write outside workspace: ${relativePath}`);
  }
  return resolved;
}
