export function renderDocs(meta: ScaffoldMeta, context: { brd?: string; architecture?: string; ux?: string }): Array<{ path: string; content: string }> {
  const docs: Array<{ path: string; content: string }> = [];
  if (context.brd) docs.push({ path: "docs/BRD.md", content: context.brd });
  if (context.architecture) docs.push({ path: "docs/ARCHITECTURE.md", content: context.architecture });
  if (context.ux) docs.push({ path: "docs/UX.md", content: context.ux });
  docs.push({
    path: "docs/GENERATED.md",
    content: `# Generated project notes\n\nEngine: **scaffold**\n\nApp: ${meta.appName}\n\nThis MVP was generated deterministically from the source requirements. Enable an LLM engine (\`AUTODEV_ENGINE=codex\`) for autonomous implementation beyond the scaffold template.\n`,
  });
  return docs;
}

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeForTemplate(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}
