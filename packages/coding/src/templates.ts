export const APP_JS = `const featuresEl = document.getElementById("features");
const clockEl = document.getElementById("clock");

function renderFeatures(features) {
  featuresEl.innerHTML = "";
  for (const feature of features) {
    const card = document.createElement("article");
    card.className = "card";
    card.dataset.testid = "feature-card";
    const title = document.createElement("h3");
    title.textContent = feature.title;
    const body = document.createElement("p");
    body.textContent = feature.description;
    card.append(title, body);
    featuresEl.append(card);
  }
}

async function load() {
  const response = await fetch("/api/meta");
  if (!response.ok) throw new Error("failed to load metadata");
  const meta = await response.json();
  renderFeatures(meta.features);
}

document.getElementById("refresh").addEventListener("click", () => {
  load().catch((error) => {
    featuresEl.innerHTML = '<p class="muted">Unable to load capabilities.</p>';
    console.error(error);
  });
});

function tick() {
  clockEl.textContent = new Date().toISOString().replace("T", " ").slice(0, 19) + " UTC";
}
tick();
setInterval(tick, 1000);

load().catch((error) => {
  featuresEl.innerHTML = '<p class="muted">Unable to load capabilities.</p>';
  console.error(error);
});
`;

