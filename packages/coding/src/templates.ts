export function renderPackageJson(meta: ScaffoldMeta): string {
  return JSON.stringify(
    {
      name: meta.appName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "generated-app",
      version: "0.1.0",
      private: true,
      // Deliberately CommonJS. The sandbox preinstalls @playwright/test and
      // exposes it through NODE_PATH, which Node's ESM resolver ignores. The
      // server is server.mjs so the app itself stays an ES module.
      description: meta.description,
      scripts: {
        start: "node server.mjs",
        test: "playwright test",
      },
    },
    null,
    2,
  );
}

export const SERVER_MJS = `import http from "node:http";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const publicDir = path.join(root, "public");
const port = Number(process.env.PORT ?? 4173);

const meta = JSON.parse(await fs.readFile(path.join(root, "app.config.json"), "utf8"));

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
};

function sendJson(res, status, body) {
  const payload = JSON.stringify(body);
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "cache-control": "no-store",
  });
  res.end(payload);
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", "http://localhost");

  if (url.pathname === "/api/health") {
    sendJson(res, 200, { status: "ok", uptimeSeconds: Math.round(process.uptime()) });
    return;
  }

  if (url.pathname === "/api/meta") {
    sendJson(res, 200, meta);
    return;
  }

  const requested = url.pathname === "/" ? "/index.html" : url.pathname;
  const resolved = path.resolve(publicDir, "." + requested);
  if (!resolved.startsWith(publicDir + path.sep) && resolved !== path.join(publicDir, "index.html")) {
    sendJson(res, 403, { error: "forbidden" });
    return;
  }

  try {
    const body = await fs.readFile(resolved);
    res.writeHead(200, { "content-type": MIME[path.extname(resolved)] ?? "application/octet-stream" });
    res.end(body);
  } catch {
    sendJson(res, 404, { error: "not found", path: url.pathname });
  }
});

server.listen(port, "0.0.0.0", () => {
  console.log("Generated app listening on http://0.0.0.0:" + port);
});

for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => server.close(() => process.exit(0)));
}
`;

