export interface ProjectFacts {
  appName: string;
  description: string;
  requirements: string;
  techStack: string[];
}

function requirementSentences(requirements: string): string[] {
  return requirements
    .split(/\r?\n|(?<=[.!?])\s+/)
    .map((line) => line.replace(/^[-*\d.)\s]+/, "").trim())
    .filter((line) => line.length >= 8);
}

function featureTitle(sentence: string): string {
  const words = sentence.split(/\s+/).slice(0, 6).join(" ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}

export function localBusinessAnalysis(facts: ProjectFacts): BusinessAnalysis {
  const sentences = requirementSentences(facts.requirements);
  const functional = sentences.slice(0, 8);
  const userStories = functional.slice(0, 6).map((sentence, index) => ({
    id: `US-${index + 1}`,
    asA: "product user",
    iWant: sentence.replace(/^the user (can|should)\s+/i, ""),
    soThat: "the described outcome is delivered",
    acceptanceCriteria: [
      `Given the application is running, when the user exercises "${featureTitle(sentence)}", then the behaviour is observable and persisted.`,
      `Given invalid input, when the user submits it, then a clear validation message is shown and no data is written.`,
    ],
  }));

  const brd = [
    `# Business Requirements Document — ${facts.appName}`,
    "",
    "## 1. Purpose",
    facts.description,
    "",
    "## 2. Scope",
    ...(functional.length > 0
      ? functional.map((sentence) => `- ${sentence}`)
      : ["- Deliver the core workflow described by the Product Owner."]),
    "",
    "## 3. Functional requirements",
    ...functional.map((sentence, index) => `FR-${index + 1}. ${sentence}`),
    "",
    "## 4. Non-functional requirements",
    "- Responsive UI usable on desktop and mobile.",
    "- Inputs are validated at the API boundary.",
    "- Errors are handled and logged without leaking secrets.",
    "- Automated end-to-end tests cover the primary flow.",
    "",
    "## 5. Stakeholders",
    "- Product Owner — approves scope and final delivery.",
    "- End users — consume the application.",
    "- AutoDev Agent — plans, builds, tests and reviews.",
    "",
    "## 6. Assumptions",
    `- The selected stack is ${facts.techStack.join(", ") || "Node.js"}.`,
    "- Authentication requirements are limited to what is stated above.",
    "",
    "## 7. Out of scope (initial MVP)",
    "- Production deployment without explicit owner approval.",
    "- Third-party integrations not named in the requirements.",
  ].join("\n");

  return {
    brd,
    userStories,
    acceptanceCriteria: userStories.flatMap((story) => story.acceptanceCriteria).slice(0, 10),
    openQuestions: functional.length < 2
      ? ["Which single user journey is most important for the first release?"]
      : [],
  };
}

