export function localQaPlan(acceptanceCriteria: string[]): QaPlan {
  const scenarios = acceptanceCriteria.slice(0, 8).map((criterion, index) => ({
    id: `TC-${index + 1}`,
    title: featureTitle(criterion),
    steps: ["Open the application", "Perform the described action", "Observe the result"],
    expected: criterion,
  }));

  if (scenarios.length === 0) {
    scenarios.push({
      id: "TC-1",
      title: "Home page renders",
      steps: ["Open the application root"],
      expected: "The application shell renders without console errors",
    });
  }

  return { scenarios, notes: "Generated from acceptance criteria; executed with Playwright." };
}

export interface ReviewInput {
  facts: ProjectFacts;
  files: Array<{ path: string; content: string }>;
  testSummary: { total: number; failed: number; passed: number } | null;
}

export function localCodeReview(input: ReviewInput): ReviewResult {
  const issues: ReviewResult["issues"] = [];
  const paths = new Set(input.files.map((file) => file.path));

  if (input.testSummary && input.testSummary.failed > 0) {
    issues.push({
      severity: "critical",
      file: null,
      issue: `${input.testSummary.failed} automated test(s) failed`,
      recommendation: "Fix the failing behaviour before requesting approval.",
    });
  }

  if (![...paths].some((path) => path.startsWith("tests/"))) {
    issues.push({
      severity: "high",
      file: null,
      issue: "No automated tests found in the project",
      recommendation: "Add Playwright tests covering the primary flow and a negative case.",
    });
  }

  if (!paths.has("README.md")) {
    issues.push({
      severity: "medium",
      file: "README.md",
      issue: "Missing README",
      recommendation: "Document setup, run and test commands.",
    });
  }

  for (const file of input.files) {
    if (/\/\.env$/.test(file.path) || file.path === ".env") {
      issues.push({
        severity: "critical",
        file: file.path,
        issue: "Environment file committed to the project",
        recommendation: "Remove it and provide a .env.example instead.",
      });
    }
    if (/(sk-[A-Za-z0-9]{16,}|AKIA[0-9A-Z]{16})/.test(file.content)) {
      issues.push({
        severity: "critical",
        file: file.path,
        issue: "Possible hardcoded API key",
        recommendation: "Read secrets from environment variables.",
      });
    }
    if (/\beval\s*\(/.test(file.content)) {
      issues.push({
        severity: "high",
        file: file.path,
        issue: "Use of eval()",
        recommendation: "Replace with explicit parsing or dispatch.",
      });
    }
    if (/console\.log\(/.test(file.content) && !file.path.startsWith("tests/")) {
      issues.push({
        severity: "low",
        file: file.path,
        issue: "Debug console.log left in source",
        recommendation: "Use a structured logger or remove the statement.",
      });
    }
  }

  const blocking = issues.some((issue) => issue.severity === "critical" || issue.severity === "high");
  return {
    verdict: blocking ? "changes_requested" : "pass",
    summary: blocking
      ? `Found ${issues.length} issue(s); ${issues.filter((i) => i.severity === "critical" || i.severity === "high").length} blocking.`
      : `Reviewed ${input.files.length} file(s) with no blocking issues.`,
    issues,
  };
}

export function localDeployment(facts: ProjectFacts): DeploymentPlan {
  const image = facts.appName.toLowerCase().replace(/[^a-z0-9]+/g, "-") || "app";
  return {
    dockerfile: [
      "FROM node:22-bookworm-slim",
      "WORKDIR /app",
      "COPY . .",
      "ENV NODE_ENV=production PORT=4173",
      "EXPOSE 4173",
      "USER node",
      'CMD ["node", "server.mjs"]',
    ].join("\n"),
    compose: [
      "services:",
      "  app:",
      `    build: .`,
      `    image: ${image}:local`,
      "    ports:",
      '      - "4173:4173"',
      "    healthcheck:",
      '      test: ["CMD", "node", "-e", "fetch(\'http://127.0.0.1:4173/api/health\').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]',
      "      interval: 30s",
      "      timeout: 5s",
      "      retries: 3",
    ].join("\n"),
    envVars: [
      { name: "PORT", required: false, description: "HTTP port, defaults to 4173" },
      { name: "NODE_ENV", required: true, description: "production" },
    ],
    healthcheck: "GET /api/health returns 200 with status=ok",
    notes:
      "Deployment artifacts are prepared but not executed. Production deployment requires explicit owner approval.",
    readyForProduction: false,
  };
}

